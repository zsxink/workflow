import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, cp, mkdir, rm, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import { createRun, readRun, currentRuntimeIdentity } from '../src/runtime/index.js';
import { prepareRunDispatch } from '../src/application/dispatch.js';
import { auditRunDispatchOutput } from '../src/application/output.js';
const exec = promisify(execFile);

test('output audit captures actual Git/files without accepting a planned attempt or changing state', async t => {
  const project = await mkdtemp(path.join(os.tmpdir(), 'workflow-output-audit-'));
  t.after(() => rm(project, { recursive: true, force: true }));
  await mkdir(path.join(project, '.workflow/changes'), { recursive: true });
  await cp('examples/change', path.join(project, '.workflow/changes/session-timeout'), { recursive: true });
  await cp('examples/config/minimal.yaml', path.join(project, '.workflow/config.yaml'));
  await cp('examples/rules.md', path.join(project, '.workflow/rules.md'));
  const git = async (...args: string[]) => exec('git', ['-C', project, ...args]);
  await git('init', '-b', 'codex/audit');
  await git('add', '.');
  await git('-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-m', 'fixture');
  const runtime = await currentRuntimeIdentity();
  const run = await createRun(project, { changeId: 'session-timeout', operationId: 'run', runtime });
  const prepared = await prepareRunDispatch(project, run.changeId, run.runId, { owner: run.owner, expectedRevision: 0, operationId: 'prepare', runtime }, { role: 'architect' });
  const design = path.join(project, '.workflow/changes/session-timeout/design.md');
  await writeFile(design, (await readFile(design, 'utf8')) + '\nAudited plan increment.\n');
  const before = await readRun(project, run.runId);
  const result = await auditRunDispatchOutput(project, run.changeId, run.runId, { dispatchId: prepared.packet.id, attemptId: prepared.packet.attemptId, runtime });
  assert.equal(result.readonly, true);
  assert.equal(result.acceptedOutput, false);
  assert.equal(result.executionReady, false);
  assert(result.changes.some(change => change.path.endsWith('/design.md') && change.kind === 'modified'));
  assert(result.diagnostics.some(d => d.code === 'OUTPUT_ATTEMPT_NOT_ATTACHED'));
  assert.deepEqual(await readRun(project, run.runId), before);
  await git('add', '.');
  const changedIndex = await auditRunDispatchOutput(project, run.changeId, run.runId, { dispatchId: prepared.packet.id, attemptId: prepared.packet.attemptId, runtime });
  assert(changedIndex.diagnostics.some(d => d.code === 'OUTPUT_INDEX_CHANGED'));
  await assert.rejects(auditRunDispatchOutput(project, run.changeId, run.runId, { dispatchId: 'missing', attemptId: 'missing', runtime }), { code: 'OUTPUT_ATTEMPT_UNKNOWN' });
});
